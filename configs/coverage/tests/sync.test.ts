import { afterEach, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import {
  coveragePackages,
  renderCodecovYaml,
  renderSummaryMarkdown,
  type SummaryRow,
} from "../src/cli.ts";

/**
 * `codecov.yml` is generated from the workspace package list, so both the
 * discovery and the rendering are pinned here: a stale component set is the
 * kind of drift nobody notices until a package silently loses its status
 * check.
 */

const roots: string[] = [];

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

function makeTree(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "coverage-sync-fixture-"));
  roots.push(root);
  for (const [relative, contents] of Object.entries(files)) {
    const path = join(root, relative);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
  return root;
}

const pkg = (name: string, scripts: Record<string, string>) =>
  JSON.stringify({ name, private: true, scripts });

describe("coveragePackages", () => {
  test("finds packages with a test or coverage script across the roots", () => {
    const root = makeTree({
      "packages/auth/package.json": pkg("@myorg/auth", { test: "mbun test" }),
      "apps/api/package.json": pkg("@myorg/api", { coverage: "mbun test --coverage" }),
    });

    expect(coveragePackages(root)).toEqual([
      { name: "api", dir: "apps/api" },
      { name: "auth", dir: "packages/auth" },
    ]);
  });

  test("skips packages without test scripts, without manifests, and unreadable ones", () => {
    const root = makeTree({
      "configs/tool/package.json": pkg("@myorg/tool", { build: "mbunup" }),
      "packages/empty/package.json": "{ not json",
      "apps/orphan/note.txt": "no manifest here",
    });

    expect(coveragePackages(root)).toEqual([]);
  });
});

describe("renderCodecovYaml", () => {
  test("renders one component per package and the shared statuses", () => {
    const yaml = renderCodecovYaml(
      [
        { name: "auth", dir: "packages/auth" },
        { name: "api", dir: "apps/api" },
      ],
      80,
    );

    expect(yaml).toContain("Generated by `mcoverage sync`");
    expect(yaml).toContain("carryforward: true");
    expect(yaml).toContain("target: 80%");
    expect(yaml).toContain('layout: "reach,diff,flags,components,tree"');
    expect(yaml).toContain("component_id: auth");
    expect(yaml).toContain('- "packages/auth/**"');
    expect(yaml).toContain("component_id: api");
    expect(yaml).toContain('- "apps/api/**"');
  });

  test("derives the status targets from the threshold it is given", () => {
    expect(renderCodecovYaml([], 90)).toContain("target: 90%");
  });

  test("renders no components when the workspace has none", () => {
    expect(renderCodecovYaml([], 80)).not.toContain("component_id:");
  });
});

describe("renderSummaryMarkdown", () => {
  const rows: SummaryRow[] = [
    { dir: "packages/auth", totals: { hit: 9, found: 10, percent: 90 } },
    { dir: "apps/api", totals: null },
  ];

  test("one row per package plus the merged total", () => {
    const markdown = renderSummaryMarkdown(rows, { hit: 19, found: 20, percent: 95 });

    expect(markdown.split("\n")).toEqual([
      "## 📊 Coverage Summary",
      "",
      "| Package | Lines |",
      "|---------|-------|",
      "| `packages/auth` | 90.00% (9/10) |",
      "| `apps/api` | — |",
      "| **merged** | **95.00% (19/20)** |",
      "",
    ]);
  });

  test("omits the merged row when there is no merged report", () => {
    expect(renderSummaryMarkdown(rows, null)).not.toContain("merged");
  });
});
